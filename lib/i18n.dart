String tr(String key) =>
    translations[appLanguage.value]?[key] ?? translations['zh']![key] ?? key;

String trf(String key, Map<String, String> args) {
  var text = tr(key);
  args.forEach((name, value) {
    text = text.replaceAll('{$name}', value);
  });
  return text;
}
